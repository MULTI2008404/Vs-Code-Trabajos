let opcion = Number(prompt("Ingrese una opción (1-5):"));
switch (opcion) {
    case 1:
        alert("Opción 1: Lunes");
        break;
    case 2:
        alert("Opción 2: Martes");
        break;
    case 3:
        alert("Opción 3: Miércoles ");
        break;
    case 4:
        alert("Opción 4: Jueves");
        break;
    case 5:
        alert("Opción 5: Viernes");
        break;
    default:
        alert("Opción no válida");
}